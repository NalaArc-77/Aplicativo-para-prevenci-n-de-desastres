function fit(X, y, lg, bal) {
  const S = st(X),
    XZ = X.map(S.Z),
    m = X[0].length,
    n = y.length,
    np = sm(y, (v) => v),
    ym = lg ? 0 : np / n,
    ys = lg ? 1 : Math.sqrt(sm(y, (v) => (v - ym) ** 2) / n) || 1,
    wt = y.map((v) => (bal ? (v ? n / (2 * np) : n / (2 * (n - np))) : 1));
  let w = Array(m + 1).fill(0);
  for (let t = 0; t < 500; t++) {
    const g = Array(m + 1).fill(0);
    XZ.forEach((r, i) => {
      let z = w[m];
      r.forEach((v, j) => (z += w[j] * v));
      const p = lg ? 1 / (1 + Math.exp(-z)) : z,
        e = (p - (y[i] - ym) / ys) * wt[i];
      r.forEach((v, j) => (g[j] += e * v));
      g[m] += e;
    });
    w = w.map((v, j) => v - (0.1 * g[j]) / n);
  }
  return (r) => {
    const x = S.Z(r);
    let z = w[m];
    x.forEach((v, j) => (z += w[j] * v));
    return lg ? 1 / (1 + Math.exp(-z)) : z * ys + ym;
  };
}
